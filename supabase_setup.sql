-- 1. Tabela de Relatos e Compromissos Comunitários
create table if not exists relatos_comunitarios (
  id bigint generated by default as identity primary key,
  nome text not null,
  localizacao text not null,
  mensagem text not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Ativar RLS (Row Level Security)
alter table relatos_comunitarios enable row level security;

-- Políticas de acesso livre (leitura e escrita anónima para sensibilização comunitária)
create policy "Permitir leitura pública dos relatos"
  on relatos_comunitarios for select
  using (true);

create policy "Permitir inserção anónima de relatos"
  on relatos_comunitarios for insert
  with check (true);

-- 2. Tabela de Estatísticas do Quiz Comunitário
create table if not exists estatisticas_quiz (
  id bigint generated by default as identity primary key,
  opcao_escolhida text not null,
  acertou boolean not null,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

alter table estatisticas_quiz enable row level security;

create policy "Permitir leitura pública das estatísticas"
  on estatisticas_quiz for select
  using (true);

create policy "Permitir envio de respostas do quiz"
  on estatisticas_quiz for insert
  with check (true);

